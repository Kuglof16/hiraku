"""Sample event streams for web/js/intake/demo.html: the intake steps of each product, made by the real code.

Nothing here is Claude's: the reasons are the code's, there is no reply from the lead, and no analysis ran.
The streams show what A1, A2 and A5 draw from the events of a run, so the screens can be looked at and
tried without a run (`python -m hiraku.intake gen-js` writes web/js/intake/demo-events.js).
"""

from __future__ import annotations

import copy
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from hiraku import contract
from hiraku.catalog import REPO_ROOT, read_data
from hiraku.intake import events as ev
from hiraku.intake import hearing, knowledge, rulecheck
from hiraku.intake.domains import pick_domains
from hiraku.intake.products import answers_file, load_product, product_files

Record = dict[str, Any]

TARGET = REPO_ROOT / "web" / "js" / "intake" / "demo-events.js"
HEADER = ("// Generated by `python -m hiraku.intake gen-js` (hiraku/intake/demo.py). Sample event streams made by the real code,\n"
          "// not runs: the reasons are the code's, there is no reply from Claude and no analysis. For demo.html only.\n")
BASE = datetime(2026, 11, 3, 10, 0, 0, tzinfo=timezone(timedelta(hours=9)))
DESIGNS = {"offroad-4w": REPO_ROOT / "data" / "designs" / "offroad-4w-v1.json"}

SAMPLE_NOTES = """# ノウハウメモ (見本)

## 板金
- 曲げの内側の半径は板厚以上
- 板金の部品は、傷が見えない向きに置く

## 電池
- 電池の質量は 30 kg 以下
"""


class _Stream:
    def __init__(self, run_id: str) -> None:
        self.run_id = run_id
        self.events: list[Record] = []

    def add(self, t: float, kind: str, *, agent: str | None = None, text: str | None = None, data: Record | None = None,
            design_version: int | None = None) -> None:
        e: Record = {"seq": len(self.events), "ts": (BASE + timedelta(seconds=t)).isoformat(timespec="milliseconds"),
                     "t": t, "run_id": self.run_id, "kind": kind}
        for k, v in (("agent", agent), ("design_version", design_version), ("text", text), ("data", data)):
            if v is not None:
                e[k] = v
        self.events.append(e)


def demo_events(slug: str, *, from_file: bool = False, label: str | None = None) -> list[Record]:
    """The intake events of one product, in the order a run would have them.

    from_file: a run started from the product's requirements file (the file stands, nothing is asked).
    """
    req = load_product(slug)
    own = {r["key"]: r for r in req["requirements"]}
    start_reqs = copy.deepcopy(req["requirements"]) if (slug == "offroad-4w" or from_file) else []
    base = copy.deepcopy(req)
    base["requirements"] = start_reqs
    path = answers_file(slug)
    answers, note = (hearing.load_answers(path) if path else ({}, None)) if not from_file else ({}, None)
    prepared = hearing.prepare(base, answers, note, product_defaults=own, ask_confirm=not from_file)
    # a run started from a file already holds the hearing's result in project.requirements
    project_reqs = copy.deepcopy(prepared.requirements_file["requirements"]) if from_file else start_reqs
    project: Record = {
        "run_id": f"20261103-100000-{label or slug}", "created_at": BASE.isoformat(timespec="milliseconds"), "want": req["want"],
        "product": slug, "flags": req["flags"], "status": "running", "round_limit": req.get("round_limit", 1),
        "cost_limit_usd": req.get("cost_limit_usd", 2.0), "cost_usd": 0.0, "requirements": project_reqs,
        "domain_picks": [], "load_cases": [], "agents": [], "design_versions": [],
    }
    if "speed_class" in req:
        project["speed_class"] = req["speed_class"]
    contract.validate("project", project)
    s = _Stream(project["run_id"])
    s.add(0.0, "run.started", agent="system", data=project)

    picked = pick_domains(req["want"], req["flags"], req.get("speed_class"))
    s.add(2.0, **_unpack(ev.picked_event(picked)))

    docs = knowledge.load_builtin()  # the contract's order: picked, knowledge, then the hearing
    for k, rec in enumerate(docs):
        s.add(3.0 + 0.2 * k, **_unpack(ev.knowledge_event(rec)))
    rules = knowledge.all_rules(docs)

    for k, event in enumerate(ev.hearing_events(prepared)):
        s.add(6.0 + 2 * k, **_unpack(event))

    if slug in DESIGNS:
        dropped = knowledge.import_text("ノウハウメモ (見本).md", SAMPLE_NOTES, doc_id="U1")
        s.add(11.0, **_unpack(ev.knowledge_event(dropped.record)))
        rules += dropped.record["rules"]
        design = read_data(DESIGNS[slug])
        s.add(12.0, "design.created", agent="designer", design_version=design["design_version"], data=design)
        ids = iter(f"rchk-{i:04d}" for i in range(1, 1000))
        for k, c in enumerate(rulecheck.check_all(rules, design, prepared.requirements_file["requirements"], id_factory=lambda: next(ids),
                                                flags=req["flags"])):
            s.add(14.0 + 0.1 * k, "rule_check.recorded", agent="packager", design_version=c["design_version"],
                  text=None, data=c)
    return s.events


def _unpack(event: Record) -> Record:
    out = {"kind": event["kind"], "agent": event.get("agent"), "text": event.get("text"), "data": event["data"]}
    return {k: v for k, v in out.items() if v is not None}


def render_js() -> str:
    demos = {slug: demo_events(slug) for slug in product_files()}
    demos["offroad-4w-file"] = demo_events("offroad-4w", from_file=True, label="offroad-4w-file")  # the video's way: the file stands
    # "\/" is the same character in JSON and in a JavaScript string; it keeps the sources' URLs (in the `basis`
    # texts) from matching the screen's rule that no external URL appears in web/ outside the pinned CDN.
    body = json.dumps(demos, ensure_ascii=False, indent=1).replace("://", ":\\/\\/")
    return f"{HEADER}export const DEMOS = {body};\n"


def write(path: Path = TARGET) -> Path:
    path.write_text(render_js(), encoding="utf-8", newline="\n")
    return path
