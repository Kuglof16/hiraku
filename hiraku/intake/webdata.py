"""The tables the intake screens (web/js/intake/) share with the code, written out as a JavaScript module.

web/js/intake/data.js is generated from the Python tables so the chips, the categories and the names of
the facts are written once. `python -m hiraku.intake gen-js` rewrites it; a test fails when it is stale.
"""

from __future__ import annotations

import json
from pathlib import Path

from hiraku import contract
from hiraku.catalog import REPO_ROOT, load_catalog
from hiraku.intake import facts
from hiraku.intake import hearing
from hiraku.intake.domains import ANALYSIS_DOMAINS
from hiraku.intake.flags import FLAG_LABELS, FLAGS, SPEED_CLASSES
from hiraku.intake.knowledge import CATEGORIES

TARGET = REPO_ROOT / "web" / "js" / "intake" / "data.js"
HEADER = "// Generated by `python -m hiraku.intake gen-js` from hiraku/intake/*.py. Do not edit; change the Python and run it again.\n"


def _flag_terms(when: str) -> dict:
    """"lean and not ride" -> {on: ["lean"], off: ["ride"]} (only `and` and `not`: the screen has no expression parser)."""
    on, off = [], []
    for term in when.split(" and "):
        words = term.split()
        if len(words) == 2 and words[0] == "not":
            off.append(words[1])
        elif len(words) == 1:
            on.append(words[0])
        else:
            raise ValueError(f"choices_if.when takes only 'flag' and 'not flag' joined by 'and': {when!r}")
    return {"on": on, "off": off}


EXAMPLE_RUN_ID = "20261105-160725-offroad-4w"  # a run Claude made whose hearing asked and was answered (its record is in showcase/)


def example_run() -> dict | None:
    """The run the 'see an example of the questions' button opens, with the numbers counted from its record."""
    path = REPO_ROOT / "showcase" / EXAMPLE_RUN_ID / "events.jsonl"
    if not path.is_file():
        return None
    asked = rounds = 0
    first_t = None  # the moment the first round of questions is answered: the exchange is whole there
    waiting = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        ev = json.loads(line)
        if ev.get("kind") == "hearing.answered" and waiting and first_t is None:
            first_t = ev["t"]
        if ev.get("kind") == "hearing.asked":
            n = sum(len(ev["data"].get(k) or []) for k in ("questions", "rule_questions", "tradeoff_questions"))
            if n:
                asked += n
                waiting = True
                rounds += 1
    return {"run": EXAMPLE_RUN_ID, "asked": asked, "rounds": rounds, "t": first_t}


def tables() -> dict:
    return {
        "EXAMPLE_RUN": example_run(),
        "FLAGS": [{"name": n, "symbol": s, "label": FLAG_LABELS[n], "question": q} for n, (s, q) in FLAGS.items()],
        "SPEED_CLASSES": [{"name": n, "symbol": s, "meaning": m} for n, (s, m) in SPEED_CLASSES.items()],
        "DOMAINS": [{"name": d, "ja": contract.DOMAIN_NAMES_JA[d]} for d in ANALYSIS_DOMAINS],
        "TESTS": {t["id"]: {"domain": t["domain"], "title": t["title"]} for t in load_catalog().tests},
        "CATEGORIES": [{"name": n, "ja": ja} for n, ja in CATEGORIES.items()],
        "ITEM_HELP": {it["key"]: {"why": it["why"], "example": str(it["example"])} for it in hearing.load_items() if it.get("why")},
        "ITEM_CHOICES_ALT": {it["key"]: {"labels": {str(k): v for k, v in it["choices_if"]["labels"].items()}, **_flag_terms(it["choices_if"]["when"])}
                             for it in hearing.load_items() if it.get("choices_if")},
        "ITEM_CHOICES": {it["key"]: {str(c["value"]): c["label"] for c in it["choices"]} for it in hearing.load_items() if it.get("choices")},
        "FACTS": {n: {"label": label, "unit": unit, "inDesigns": scope != "declared"}
                  for n, (label, unit, scope) in facts.FACTS.items()},
    }


def render_js() -> str:
    parts = [HEADER]
    for name, value in tables().items():
        parts.append(f"export const {name} = {json.dumps(value, ensure_ascii=False, indent=2)};\n")
    return "\n".join(parts)


def write(path: Path = TARGET) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_js(), encoding="utf-8", newline="\n")
    return path
