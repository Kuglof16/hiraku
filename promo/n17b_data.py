"""Count how much went into HIRAKU and how deep one run goes, for the N17b screen.

Two sources, both read by code (nothing typed in by hand):

- the git record of one ref (main by default): the amount (sentence 1 of the
  voice)
- the record of one run (its events.jsonl): the depth (sentence 2)

and writes promo/screens/n17b.data.js (``window.N17B_DATA = {...}``), which
n17b.html loads with <script src> (the screen is opened from file://).

    py promo/n17b_data.py --run <runs/<run_id> folder>
    py promo/n17b_data.py --run <folder> --ref main --out promo/screens/n17b.data.js

The amount, from git (``amount``):

- lines: lines of the tracked files of the ref (git ls-tree -r, the list git
  ls-files gives on a checkout of it), by language from the file's extension
  (.py, .js, .mjs, .html, .css). Blank lines and comments are included. Files
  whose first two lines say they are generated are left out.
- commits: every commit reachable from the ref (git log <ref>), merges
  included, and how many of them are merges (more than one parent).
- days: calendar days (JST) from the first commit to the ref's newest commit,
  both counted (2026-11-02 to 2026-11-03 is day 2).
- tests: lines that define a test (``def test_``) in the tracked Python files.

The depth, from the run's events.jsonl (``depth``). A record that is put out
again with the same ID (docs/contract.md: the last event of an ID is the
record) is counted once, as its last event:

- areas: the domains in the last ``domains.picked`` (data.picks), and whether
  assembly is judged too (a ``judgement.updated`` of domain "assembly").
- passed: of the areas, how many are "green" in their last
  ``judgement.updated`` of the newest design version; versions: the number of
  ``design.created`` (the first design and each fix).
- tools: the analysis tools of the run, the last ``tool.checked`` of each name
  (data.name) that says usable; known_cases: the known-answer cases those
  tools were checked against before use (data.checks, all passed).
- comparisons: hand calculation (prediction) set against the analysis, one per
  comparison_id of ``comparison.recorded``; mismatches: those with status
  "mismatch"; explained: the mismatches whose cause was recorded and is
  resolved (``cause.recorded``, data.resolved).
- predictions: one per prediction_id of ``prediction.recorded``.

counted_at: when this script ran (JST); head: the ref's newest commit; run_id:
the run's ID (the name of its folder, data.run_id of its events). Run it again
at the freeze to bring the numbers up to date. No author names or e-mail
addresses are read or written, and no paths are written into the data.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "screens" / "n17b.data.js"
JST = timezone(timedelta(hours=9))

# Languages counted as written code, by file extension.
LANGUAGES = {
    ".py": "Python",
    ".js": "JavaScript",
    ".mjs": "JavaScript",
    ".html": "HTML",
    ".css": "CSS",
}
# "// Generated file: ...", "# Generated by ...": a comment that starts with the word
GENERATED = re.compile(r"^\s*(?://|#|/\*|<!--|\*)?\s*generated\b", re.I)
TEST_DEF = re.compile(r"^\s*(?:async\s+)?def\s+test_", re.M)
ASSEMBLY = "assembly"


def git(repo: Path, *args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(["git", "-C", str(repo), *args], input=data, capture_output=True, check=True).stdout


# --- the amount, from git ---------------------------------------------------------

def read_log(repo: Path, ref: str) -> list[dict]:
    """Commits reachable from ref: [{sha, parents, at (author time), ct (commit time)}]."""
    out = git(repo, "log", ref, "--format=%H%x1f%P%x1f%at%x1f%ct")
    commits = []
    for line in out.decode("utf-8").splitlines():
        sha, parents, at, ct = line.split("\x1f", 3)
        commits.append({"sha": sha, "parents": parents.split(), "at": int(at), "ct": int(ct)})
    return commits


def tree_blobs(repo: Path, ref: str) -> list[tuple[str, str]]:
    """(path, blob id) of every tracked file of ref."""
    out = git(repo, "ls-tree", "-r", "--full-tree", ref).decode("utf-8")
    files = []
    for line in out.splitlines():
        meta, path = line.split("\t", 1)
        _mode, kind, oid = meta.split()
        if kind == "blob":
            files.append((path, oid))
    return files


def read_blobs(repo: Path, oids: list[str]) -> dict[str, bytes]:
    """Contents of blobs by id (one git cat-file --batch)."""
    if not oids:
        return {}
    raw = git(repo, "cat-file", "--batch", data=("\n".join(oids) + "\n").encode())
    out, i = {}, 0
    for oid in oids:
        j = raw.index(b"\n", i)
        head = raw[i:j].split()
        size = int(head[2])
        out[oid] = raw[j + 1:j + 1 + size]
        i = j + 1 + size + 1
    return out


def count_lines(data: bytes) -> int:
    """Lines in a file (a last line without a newline counts)."""
    if not data:
        return 0
    return data.count(b"\n") + (0 if data.endswith(b"\n") else 1)


def is_generated(data: bytes) -> bool:
    """The file's first two lines say it is generated."""
    head = data[:600].decode("utf-8", "replace").splitlines()[:2]
    return any(GENERATED.search(h) for h in head)


def count_tree(repo: Path, ref: str) -> dict:
    files = tree_blobs(repo, ref)
    blobs = read_blobs(repo, [oid for _p, oid in files])
    lines: dict[str, int] = {}
    skipped, tests = [], 0
    for path, oid in files:
        data = blobs[oid]
        ext = Path(path).suffix.lower()
        if ext == ".py":
            tests += len(TEST_DEF.findall(data.decode("utf-8", "replace")))
        lang = LANGUAGES.get(ext)
        if not lang:
            continue
        if is_generated(data):
            skipped.append(path)
            continue
        lines[lang] = lines.get(lang, 0) + count_lines(data)
    order = sorted(lines, key=lambda k: -lines[k])
    return {
        "lines": {k: lines[k] for k in order},
        "lines_total": sum(lines.values()),
        "generated_skipped": sorted(skipped),
        "tests": tests,
    }


def iso(ts: int) -> str:
    return datetime.fromtimestamp(ts, JST).isoformat(timespec="seconds")


def amount(repo: Path, ref: str) -> dict:
    commits = read_log(repo, ref)
    if not commits:
        raise SystemExit(f"no commits in {ref}")
    head = git(repo, "rev-parse", ref).decode().strip()
    head_c = next(c for c in commits if c["sha"] == head)
    t0 = min(c["at"] for c in commits)
    d0 = datetime.fromtimestamp(t0, JST).date()
    d1 = datetime.fromtimestamp(head_c["ct"], JST).date()
    return {
        "head": head[:7],
        "head_time": iso(head_c["ct"]),
        "first_commit": iso(t0),
        "days": (d1 - d0).days + 1,
        "commits": len(commits),
        "merges": sum(1 for c in commits if len(c["parents"]) > 1),
        **count_tree(repo, ref),
    }


# --- the depth, from one run's record -----------------------------------------------

def read_events(run: Path) -> list[dict]:
    with open(run / "events.jsonl", encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def last_by(events: list[dict], kind: str, key: str) -> dict[str, dict]:
    """data of the last event of each ID (data[key]) of one kind."""
    out: dict[str, dict] = {}
    for e in events:
        if e.get("kind") == kind:
            out[e["data"][key]] = e["data"]
    return out


def depth(events: list[dict]) -> dict:
    picked = [e["data"] for e in events if e.get("kind") == "domains.picked"]
    if not picked:
        raise SystemExit("the run has no domains.picked")
    picks = picked[-1]["picks"]
    judged = [e["data"] for e in events if e.get("kind") == "judgement.updated"]
    with_assembly = any(j["domain"] == ASSEMBLY for j in judged)
    areas = [p["domain"] for p in picks] + ([ASSEMBLY] if with_assembly else [])

    newest = max((j["design_version"] for j in judged), default=0)
    state = {}
    for j in judged:
        if j["design_version"] == newest:
            state[j["domain"]] = j["state"]
    passed = sum(1 for a in areas if state.get(a) == "green")

    tools = {name: t for name, t in last_by(events, "tool.checked", "name").items() if t.get("usable")}
    cases = [c for t in tools.values() for c in t.get("checks", [])]
    if not all(c.get("pass") for c in cases):
        raise SystemExit("a usable tool has a known-answer case that did not pass")

    comps = last_by(events, "comparison.recorded", "comparison_id")
    causes = last_by(events, "cause.recorded", "cause_id")
    mism = [c for c in comps.values() if c["status"] == "mismatch"]
    explained = [c for c in mism if c.get("cause_id") and causes.get(c["cause_id"], {}).get("resolved")]

    run_ids = {e.get("run_id") for e in events if e.get("run_id")}
    return {
        "run_id": sorted(run_ids)[0] if len(run_ids) == 1 else None,
        "domains": len(picks),
        "domain_names": [p["shown_name"] for p in picks],
        "assembly": with_assembly,
        "areas": len(areas),
        "passed": passed,
        "versions": sum(1 for e in events if e.get("kind") == "design.created"),
        "tools": len(tools),
        "known_cases": len(cases),
        "comparisons": len(comps),
        "mismatches": len(mism),
        "explained": len(explained),
        "predictions": len(last_by(events, "prediction.recorded", "prediction_id")),
    }


# --- all of it ---------------------------------------------------------------------

def collect(run: Path, repo: Path = ROOT, ref: str = "main", now: datetime | None = None) -> dict:
    now = now or datetime.now(JST)
    return {
        "ref": ref,
        "counted_at": now.astimezone(JST).isoformat(timespec="minutes"),
        "amount": amount(repo, ref),
        "depth": depth(read_events(run)),
    }


def render_js(data: dict) -> str:
    return ("// Generated file: do not edit. Written by promo/n17b_data.py from the git record "
            f"of {data['ref']} ({data['amount']['head']}) and the run {data['depth']['run_id']}.\n"
            "window.N17B_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", type=Path, required=True, help="the run's folder (holds events.jsonl)")
    ap.add_argument("--repo", type=Path, default=ROOT)
    ap.add_argument("--ref", default="main")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    data = collect(a.run, a.repo, a.ref)
    a.out.write_text(render_js(data), encoding="utf-8", newline="\n")
    am, dp = data["amount"], data["depth"]
    print(f"{data['ref']} {am['head']} counted at {data['counted_at']}")
    print(f"  amount: {am['lines_total']:,} lines ("
          + ", ".join(f"{k} {v:,}" for k, v in am["lines"].items())
          + f"), {am['commits']} commits ({am['merges']} merges), day {am['days']}, {am['tests']:,} tests")
    print(f"  generated files left out: {', '.join(am['generated_skipped']) or 'none'}")
    print(f"  depth ({dp['run_id']}): {dp['domains']} domains"
          + (" + assembly" if dp["assembly"] else "")
          + f", {dp['passed']}/{dp['areas']} green in version {dp['versions']}, "
          f"{dp['tools']} tools checked on {dp['known_cases']} known-answer cases, "
          f"{dp['comparisons']} comparisons ({dp['mismatches']} mismatches, {dp['explained']} explained), "
          f"{dp['predictions']} predictions")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
